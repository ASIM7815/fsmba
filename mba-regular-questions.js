// Function to select exam questions for MBA Regular students
// Distribution: 3 from M1, 3 from M2, 4 from M3, 4 from M4, 3 from M5, 3 from M6 = 20 questions
function selectMBARegularExamQuestions() {
    let selectedQuestions = [];
    
    // Module 1: 3 questions
    let m1Selected = selectRandomQuestions(mbaRegularModule1, 3);
    selectedQuestions = selectedQuestions.concat(m1Selected);
    
    // Module 2: 3 questions
    let m2Selected = selectRandomQuestions(mbaRegularModule2, 3);
    selectedQuestions = selectedQuestions.concat(m2Selected);
    
    // Module 3: 4 questions
    let m3Selected = selectRandomQuestions(mbaRegularModule3, 4);
    selectedQuestions = selectedQuestions.concat(m3Selected);
    
    // Module 4: 4 questions
    let m4Selected = selectRandomQuestions(mbaRegularModule4, 4);
    selectedQuestions = selectedQuestions.concat(m4Selected);
    
    // Module 5: 3 questions
    let m5Selected = selectRandomQuestions(mbaRegularModule5, 3);
    selectedQuestions = selectedQuestions.concat(m5Selected);
    
    // Module 6: 3 questions
    let m6Selected = selectRandomQuestions(mbaRegularModule6, 3);
    selectedQuestions = selectedQuestions.concat(m6Selected);
    
    return selectedQuestions;
}

// Helper function to select random questions from a module
function selectRandomQuestions(moduleQuestions, count) {
    let shuffled = [...moduleQuestions];
    
    // Fisher-Yates shuffle
    for (let i = shuffled.length - 1; i > 0; i--) {
        let j = Math.floor(Math.random() * (i + 1));
        [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }
    
    return shuffled.slice(0, count);
}
